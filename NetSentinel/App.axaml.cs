using Avalonia;
using Avalonia.Controls.ApplicationLifetimes;
using Avalonia.Data.Core.Plugins;
using System.Linq;
using Avalonia.Markup.Xaml;
using Microsoft.Extensions.DependencyInjection;
using System;
using NetSentinel.ViewModels;
using NetSentinel.Views;
using NetSentinel.Services;
using NetSentinel.Database;
using Microsoft.Extensions.Hosting;
using Microsoft.Extensions.Configuration;
using Microsoft.EntityFrameworkCore;
using ShadUI;

namespace NetSentinel;

/// <summary>
/// Entry point for the Avalonia GUI Framework app.
/// Purpose: A place to set up dependency injection 
/// and register viewmodels and services etc.
/// </summary>

public partial class App : Application
{
    public IServiceProvider? Services { get; private set; }

    public override void Initialize()
    {
        AvaloniaXamlLoader.Load(this);
    }

    public override void OnFrameworkInitializationCompleted()
    {
        // SETUP DEPENDENCY INJECTION
        var builder = Host.CreateApplicationBuilder();
        var connectionString = builder.Configuration.GetConnectionString("DefaultConnection");

        // Register services, viewmodels etc
        builder.Services.AddSingleton<NavigationService>(sp => new NavigationService(sp));
        builder.Services.AddSingleton<DialogManager>();
        builder.Services.AddSingleton<ToastManager>();
        builder.Services.AddDbContext<DatabaseContext>(options => options.UseSqlServer(connectionString));
        builder.Services.AddTransient<MainWindowViewModel>();
        builder.Services.AddTransient<DashboardViewModel>();
        builder.Services.AddTransient<DevicesViewModel>();
        builder.Services.AddTransient<SettingsViewModel>();
        builder.Services.AddTransient<DeviceDialogViewModel>();
        builder.Services.AddTransient<DepartmentDialogViewModel>();
        builder.Services.AddTransient<DepartmentsViewModel>();
        builder.Services.AddTransient<EmployeesViewModel>();
        builder.Services.AddTransient<SecurityMeasuresViewModel>();
        builder.Services.AddTransient<SecurityMeasureDialogViewModel>();
        builder.Services.AddTransient<EmployeeDialogViewModel>();
        builder.Services.AddScoped<DeviceService>();
        builder.Services.AddScoped<DepartmentService>();
        builder.Services.AddScoped<EmployeeService>();
        builder.Services.AddScoped<SecurityMeasureService>();
        builder.Services.AddScoped<IncidentService>();

        // 2. Build the Service Provider
        Services = builder.Services.BuildServiceProvider();

        // Register dialogs
        var dialogManager = Services.GetRequiredService<DialogManager>();
        dialogManager.Register<DeviceDialogView, DeviceDialogViewModel>();
        dialogManager.Register<DepartmentDialogView, DepartmentDialogViewModel>();
        dialogManager.Register<SecurityMeasureDialogView, SecurityMeasureDialogViewModel>();
        dialogManager.Register<EmployeeDialogView, EmployeeDialogViewModel>();

        // 3. Use the service provider to create the main window and set its DataContext
        if (ApplicationLifetime is IClassicDesktopStyleApplicationLifetime desktop)
        {
            DisableAvaloniaDataAnnotationValidation();
            desktop.MainWindow = new MainWindow { DataContext = Services.GetRequiredService<MainWindowViewModel>() };
            Services.GetRequiredService<NavigationService>().GoToDashboard();
        }

        base.OnFrameworkInitializationCompleted();
    }

    // Helper method generated by Avalonia
    private void DisableAvaloniaDataAnnotationValidation()
    {
        // 1. Find the specific plugin that handles Data Annotations
        var dataValidationPluginsToRemove =
            BindingPlugins.DataValidators.OfType<DataAnnotationsValidationPlugin>().ToArray();

        // 2. Remove it from Avalonia's list of active validators
        foreach (var plugin in dataValidationPluginsToRemove)
        {
            BindingPlugins.DataValidators.Remove(plugin);
        }
    }
}